// Test to understand cart structure
const mongoose = require('mongoose');

// Simulate cart schema
const cartSchema = new mongoose.Schema({
  userId: { type: mongoose.Schema.Types.ObjectId, ref: "User" },
  items: [
    {
      productId: { type: mongoose.Schema.Types.ObjectId, ref: "Product" },
      designId: { type: mongoose.Schema.Types.ObjectId, ref: "Design" },
      quantity: Number,
      size: String,
      color: String,
      addedAt: { type: Date, default: Date.now },
    },
  ],
  updatedAt: { type: Date, default: Date.now },
});

console.log('Cart Item Structure:');
console.log('- Each item in cart.items array has its own _id (auto-generated by MongoDB)');
console.log('- To update an item, you need that specific item._id');
console.log('- cart.items.id(itemId) finds the subdocument by its _id');
console.log('\nExample:');
console.log('Cart: { _id: "cart123", items: [');
console.log('  { _id: "item1", productId: "prod1", quantity: 2 },');
console.log('  { _id: "item2", productId: "prod2", quantity: 3 }');
console.log('] }');
console.log('\nTo update item2, use: PUT /api/customer/cart/item2');
